/**
 * Exports current items in the table to an Excel file with 3-way comparison
 */
export function exportCurrentDataToExcel(items: BudgetItem[], totalExpense: number, totalIncome: number) {
  let total69 = 0;
  let totalAct69 = 0;

  items.forEach((item) => {
    if (!item.isMain) {
      total69 += item.budget69 || 0;
      totalAct69 += item.actual69 || 0;
    }
  });

  const exportRows = items.map((item, index) => {
    const b69 = item.budget69 || 0;
    const act69 = item.actual69 || 0;
    const b70 = item.budget;
    const disburseRate = b69 > 0 ? ((act69 / b69) * 100).toFixed(1) + '%' : '-';
    const diffVsReq69 = b70 - b69;
    const diffVsAct69 = act69 > 0 ? b70 - act69 : b70;

    return {
      'ลำดับ': item.isMain ? '' : index + 1,
      'ประเภท': item.isMain ? 'หมวดหมู่หลัก' : 'รายการย่อย',
      'รหัสโครงการ': item.id,
      'หมวดหมู่สังกัด': item.parentName,
      'รายการกิจกรรม': item.activity,
      'คำของบประมาณปี 2569 (บาท)': b69,
      'จ่ายจริงปี 2569 (บาท)': act69,
      'อัตราเบิกจ่ายปี 69': disburseRate,
      'คำของบประมาณปี 2570 (บาท)': b70,
      'ผลต่าง (คำขอ 70 vs คำขอ 69)': diffVsReq69,
      'ผลต่าง (คำขอ 70 vs จ่ายจริง 69)': diffVsAct69,
    };
  });

  // Append summary row
  exportRows.push({
    'ลำดับ': '' as any,
    'ประเภท': 'สรุปภาพรวม',
    'รหัสโครงการ': 'TOTAL',
    'หมวดหมู่สังกัด': `ประมาณการรายรับ: ฿${totalIncome.toLocaleString('th-TH')}`,
    'รายการกิจกรรม': `รวมงบประมาณรายจ่ายทั้งสิ้น (เฉพาะรายการย่อย) | คงเหลือ: ฿${(totalIncome - totalExpense).toLocaleString('th-TH')}`,
    'คำของบประมาณปี 2569 (บาท)': total69,
    'จ่ายจริงปี 2569 (บาท)': totalAct69,
    'อัตราเบิกจ่ายปี 69': total69 > 0 ? ((totalAct69 / total69) * 100).toFixed(1) + '%' : '-',
    'คำของบประมาณปี 2570 (บาท)': totalExpense,
    'ผลต่าง (คำขอ 70 vs คำขอ 69)': totalExpense - total69,
    'ผลต่าง (คำขอ 70 vs จ่ายจริง 69)': totalExpense - totalAct69,
  });

  const ws = XLSX.utils.json_to_sheet(exportRows);

  ws['!cols'] = [
    { wch: 8 },
    { wch: 14 },
    { wch: 16 },
    { wch: 45 },
    { wch: 60 },
    { wch: 24 },
    { wch: 22 },
    { wch: 18 },
    { wch: 24 },
    { wch: 26 },
    { wch: 26 },
  ];

  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'เปรียบเทียบงบประมาณ');

  XLSX.writeFile(wb, `รายงานเปรียบเทียบงบประมาณ_2569_2570_${new Date().toISOString().slice(0, 10)}.xlsx`);
}

